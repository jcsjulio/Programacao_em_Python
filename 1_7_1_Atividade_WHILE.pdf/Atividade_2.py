# Requisito: Inicie a variável com o valor 10
contador = 10

# Requisito: Utilize WHILE para realizar a contagem de 10 até 0
while contador >= 0:
    # Requisito: Mostre cada número na tela
    print(contador)
    # Decrementa a variável para descer até zero
    contador -= 1

# Requisito: Ao finalizar, exiba a mensagem: "FIM!"
print("FIM!")

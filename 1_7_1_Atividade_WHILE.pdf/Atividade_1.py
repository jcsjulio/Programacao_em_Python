# Requisito: Crie uma variável iniciando com o valor 1
contador = 1

# Requisito: Utilize WHILE para controlar a repetição (de 1 até 10)
while contador <= 10:
    # Requisito: Mostre cada número na tela
    print(contador)
    # Requisito: Incremente a variável a cada repetição
    contador += 1

